"""Turn the notebook's CSVs (data/catalog_csv) into one SQL file for the Supabase SQL editor.

    python scripts/csv_to_seed_sql.py data/catalog_csv > supabase/seed/catalog_seed_osm.sql

Rows are upserted by id, so re-running after rebuilding the dataset updates prices and menus.
"""
import csv
import sys
from pathlib import Path

MAP = {  # table: (csv file, {db column: csv column})
    "venues": ("venues.csv", {"id": "venue_id", "name": "name", "address": "address", "lat": "lat", "lng": "lng",
                              "capacity": "capacity"}),
    "hotels": ("hotels.csv", {"id": "hotel_id", "venue_id": "venue_id", "name": "name", "address": "address",
                              "lat": "lat", "lng": "lng", "stars": "stars", "price_per_night": "price_per_room_night",
                              "room_capacity": "room_capacity", "rooms_available": "rooms_available",
                              "amenities": "amenities", "cancellation_policy": "cancellation_policy",
                              "source": "source", "osm_id": "osm_id"}),
    "restaurants": ("restaurants.csv", {"id": "restaurant_id", "venue_id": "venue_id", "name": "name",
                                        "address": "address", "lat": "lat", "lng": "lng", "cuisine": "cuisine",
                                        "halal_certified": "halal_certified", "group_capacity": "group_capacity",
                                        "takes_group_reservations": "takes_group_reservations",
                                        "price_per_person": "price_per_head", "source": "source", "osm_id": "osm_id"}),
    "menu_items": ("menu_items.csv", {"id": "item_id", "restaurant_id": "restaurant_id", "name": "name",
                                      "course": "course", "price": "price", "diet_tags": "diet_tags"}),
    "bus_options": ("bus_options.csv", {"id": "bus_option_id", "company": "company", "vehicle": "vehicle",
                                        "seats": "seats", "rate_per_km": "rate_per_km", "min_charge": "min_charge",
                                        "driver_overnight_fee": "driver_overnight_fee", "wifi": "wifi",
                                        "luggage_bay": "luggage_bay"}),
}
NULLABLE = {"osm_id", "capacity", "stars"}


def lit(col, value):
    if value == "":
        return "null" if col in NULLABLE else "''"
    if value in ("True", "False"):
        return value.lower()
    try:
        float(value)
        return value
    except ValueError:
        return "'" + value.replace("'", "''") + "'"


def main(folder):
    out = ["-- Generated by scripts/csv_to_seed_sql.py. Upserts by id; safe to re-run.", "begin;"]
    for table, (fname, cols) in MAP.items():
        rows = list(csv.DictReader(open(Path(folder) / fname, newline="", encoding="utf-8")))
        if table == "venues":
            rows = [r for r in rows if r["venue_id"] != "V_HOME"]      # the home campus lives on teams, not venues
        values = ",\n".join("(" + ",".join(lit(c, r[src]) for c, src in cols.items()) + ")" for r in rows)
        updates = ", ".join(f"{c} = excluded.{c}" for c in cols if c != "id")
        out.append(f"insert into public.{table} ({', '.join(cols)}) values\n{values}\n"
                   f"on conflict (id) do update set {updates};")
    out.append("commit;")
    print("\n\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/catalog_csv")
